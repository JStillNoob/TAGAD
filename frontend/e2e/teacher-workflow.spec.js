import { accounts, createMinimalPdf, expect, login, logout, test } from './support.js'


test('teacher runs a simulator-only session, sees provenance, reports, and logs out', async ({ page }, testInfo) => {
  const pdfPath = testInfo.outputPath('browser-presentation.pdf')
  await createMinimalPdf(pdfPath)
  await login(page, accounts.teacher)

  await page.getByRole('link', { name: 'Live Session' }).click()
  await expect(page).toHaveURL(/\/session$/)
  await page.getByLabel('Title').fill('E2E Session Slides')
  await page.getByLabel('File').setInputFiles(pdfPath)
  await page.getByRole('button', { name: 'Upload Presentation' }).click()
  await expect(page.getByText('E2E Session Slides', { exact: true })).toBeVisible()
  await expect(page.getByText('1 generated slides')).toBeVisible()

  const sessionDetails = page.getByRole('heading', { name: 'Session Details' }).locator('..')
  const subjectSelect = sessionDetails.locator('select').nth(0)
  const subjectValue = await subjectSelect.locator('option').filter({ hasText: 'E2E-IT101' }).getAttribute('value')
  await subjectSelect.selectOption(subjectValue)
  await expect(page.getByText('1/1 selected', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Clear', exact: true }).click()
  await expect(page.getByText('0/1 selected', { exact: true })).toBeVisible()
  const presentationSelect = sessionDetails.locator('select').nth(1)
  const presentationValue = await presentationSelect.locator('option').filter({ hasText: 'E2E Session Slides' }).getAttribute('value')
  await presentationSelect.selectOption(presentationValue)
  await page.getByRole('button', { name: 'Prepare Session', exact: true }).click()
  await expect(page.getByText('Review mode · session timing and analytics have not started')).toBeVisible()
  await expect(page.getByText('Slide 1 of 1')).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Camera & Worker Health' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Start Session', exact: true })).toBeEnabled()

  await page.reload()
  await expect(page.getByText('Review mode · session timing and analytics have not started')).toBeVisible()
  await expect(page.getByText('Slide 1 of 1')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Start Session', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Start Session', exact: true }).click()
  const countdownDialog = page.getByRole('dialog', { name: 'Your classroom session is about to begin' })
  await expect(countdownDialog).toBeVisible()
  await expect(countdownDialog.getByText('5', { exact: true })).toBeVisible()
  await countdownDialog.getByRole('button', { name: 'Cancel session start' }).click()
  await expect(countdownDialog).toBeHidden()
  await expect(page.getByRole('button', { name: 'End Session' })).toHaveCount(0)

  await page.getByRole('button', { name: 'Start Session', exact: true }).click()
  await expect(countdownDialog).toBeVisible()
  await expect(page.getByRole('button', { name: 'End Session' })).toBeVisible()
  await expect(page.getByText('Slide 1 of 1')).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Camera & Worker Health' })).toBeVisible()
  await expect(page.getByText('Simulator only', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Start Simulation' })).toBeVisible()

  await page.reload()
  await expect(page.getByRole('button', { name: 'End Session' })).toBeVisible()
  await expect(page.getByText('Slide 1 of 1')).toBeVisible()
  await expect(page.getByText('Simulator only', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Start Simulation' }).click()
  await expect(page.getByRole('button', { name: 'Stop Simulation' })).toBeVisible()
  await expect(page.getByText(/detected · \d+ unclassified · Slide 1/)).toBeVisible()

  page.once('dialog', (dialog) => dialog.accept())
  await page.getByRole('button', { name: 'End Session' }).click()
  await expect(page).toHaveURL(/\/analytics\?session=\d+$/)
  await expect(page.getByText('Students Detected')).toBeVisible()
  await expect(page.getByText('Development simulation', { exact: true })).toBeVisible()
  await expect(page.getByText('Development simulation — not official classroom analytics.')).toBeVisible()
  await expect(page.getByText('Data quality: Insufficient')).toBeVisible()
  await expect(page.getByText('Classification Coverage')).toBeVisible()
  await expect(page.getByRole('columnheader', { name: 'Unclassified' })).toBeVisible()
  await expect(page.getByText('Insights withheld')).toBeVisible()

  await page.getByRole('link', { name: 'Reports' }).click()
  const generatedResponsePromise = page.waitForResponse(response => (
    response.url().endsWith('/api/auth/reports/')
    && response.request().method() === 'POST'
  ))
  await page.getByRole('button', { name: 'Generate polished PDF' }).click()
  const generatedReport = await (await generatedResponsePromise).json()
  await expect(page.getByRole('status')).toContainText('Polished PDF report generated successfully')
  const reportRow = page.getByRole('row').filter({ hasText: generatedReport.file_name })
  await expect(reportRow).toHaveCount(1)

  page.once('dialog', dialog => dialog.accept())
  await reportRow.getByRole('button', { name: 'Delete' }).click()
  await expect(page.getByText(generatedReport.file_name, { exact: true })).toHaveCount(0)

  await page.getByRole('link', { name: 'Live Session' }).click()
  const presentationLibrary = page.getByRole('region', { name: 'Presentation Library' })
  const presentationCard = presentationLibrary.locator('div.rounded-lg').filter({ hasText: 'E2E Session Slides' }).first()
  page.once('dialog', dialog => dialog.accept())
  await presentationCard.getByRole('button', { name: 'Archive' }).click()
  await presentationLibrary.getByLabel('Presentation records').selectOption('archived')
  const archivedPresentation = presentationLibrary.locator('div.rounded-lg').filter({ hasText: 'E2E Session Slides' }).first()
  await archivedPresentation.getByRole('button', { name: 'Restore' }).click()

  const recentSessions = page.getByRole('region', { name: 'Recent Sessions' })
  const sessionCard = recentSessions.locator('div.rounded-lg').filter({ hasText: 'E2E-IT101' }).first()
  page.once('dialog', dialog => dialog.accept())
  await sessionCard.getByRole('button', { name: 'Archive' }).click()
  await recentSessions.getByLabel('Session records').selectOption('archived')
  const archivedSession = recentSessions.locator('div.rounded-lg').filter({ hasText: 'E2E-IT101' }).first()
  await archivedSession.getByRole('button', { name: 'Restore' }).click()
  await logout(page)
})
